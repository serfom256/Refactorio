package cleancomments

import "strings"

var directivePrefixes = []string{
	"go:", "#!", "nolint", "lint:", "+build", "#!", "noqa", "type:", "pragma",
	"eslint", "prettier-ignore", "@ts-", "tslint:", "jshint", "global ",
	"istanbul ", "c8 ", "v8 ", "deno-", "biome-ignore", "codegen",
	"swagger:", "@router", "@summary", "@success", "@failure", "@accept",
	"@produce", "@securitydefinitions", "@basepath",
	"cgo", "export ", "revive:", "staticcheck", "gocyclo", "coverage:",
	"clippy::", "allow(", "deny(", "warn(", "rustfmt::", "cfg_attr",
	"region", "endregion", "pylint:", "mypy:", "fmt:", "autogenerated",
	"code generated", "do not edit", "ruff:", "deprecated:",
}

var licenceOpeners = []string{
	"copyright", "license", "licence", "licensed", "spdx", "@license",
	"all rights reserved", "(c) 20", "© 20",
}

var licencePhrases = []string{
	"spdx-license-identifier", "all rights reserved",
	"apache license", "gnu general public", "mozilla public license",
}

var markerOpeners = []string{"todo", "fixme", "hack", "xxx", "@todo", "@fixme"}

func Keep(text string) (string, bool) {
	if isDirective(text) {
		return "directive", true
	}
	stripped := stripMarkers(text)
	lower := strings.ToLower(stripped)
	for _, w := range licencePhrases {
		if strings.Contains(lower, w) {
			return "licence header", true
		}
	}
	if opensWith(lower, licenceOpeners) {
		return "licence header", true
	}
	if opensWith(lower, markerOpeners) {
		return "TODO/FIXME", true
	}
	return "", false
}

func opensWith(text string, words []string) bool {
	for _, w := range words {
		if !strings.HasPrefix(text, w) {
			continue
		}
		rest := text[len(w):]
		if rest == "" || !isWordByte(rest[0]) {
			return true
		}
	}
	return false
}

func isDirective(text string) bool {
	candidates := []string{
		strings.ToLower(strings.TrimSpace(stripMarkers(text))),
		strings.ToLower(strings.TrimSpace(text)),
	}
	for _, c := range candidates {
		for _, p := range directivePrefixes {
			if strings.HasPrefix(c, p) {
				return true
			}
		}
	}
	return false
}

func hasWord(text, word string) bool {
	for i := 0; i <= len(text)-len(word); {
		j := strings.Index(text[i:], word)
		if j < 0 {
			return false
		}
		start, end := i+j, i+j+len(word)
		beforeOK := start == 0 || !isWordByte(text[start-1])
		afterOK := end == len(text) || !isWordByte(text[end])
		if beforeOK && afterOK {
			return true
		}
		i = end
	}
	return false
}

func isWordByte(b byte) bool {
	return b == '_' ||
		(b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z') || (b >= '0' && b <= '9')
}

func stripMarkers(text string) string {
	var b strings.Builder
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		line = strings.TrimPrefix(line, "/***")
		line = strings.TrimPrefix(line, "/**")
		line = strings.TrimPrefix(line, "/*")
		line = strings.TrimSuffix(line, "*/")
		line = strings.TrimPrefix(line, "///")
		line = strings.TrimPrefix(line, "//!")
		line = strings.TrimPrefix(line, "//")
		line = strings.TrimPrefix(line, "#")
		for _, q := range []string{`"""`, `'''`} {
			line = strings.TrimPrefix(line, q)
			line = strings.TrimSuffix(line, q)
		}
		line = strings.TrimSpace(line)
		line = strings.TrimPrefix(line, "*")
		b.WriteString(strings.TrimSpace(line))
		b.WriteString(" ")
	}
	return strings.TrimSpace(b.String())
}

func isPinned(text string) bool {
	_, keep := Keep(text)
	return keep
}
