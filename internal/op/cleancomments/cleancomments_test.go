func TestScan_KeepsDocstringThatIsTheWholeBody(t *testing.T) {
	dir := t.TempDir()
	p := write(t, dir, "c.py", `def stub():
    """Not implemented yet."""


def real():
    """Doc."""
    return 1
`)
	removed, kept := scan(t, p)
	if !strings.Contains(kept[2], "empty a Python block") {
		t.Errorf("line 2 kept as %q; removing it would leave def stub() with no body", kept[2])
	}
	if _, ok := removed[6]; !ok {
		t.Error("line 6 has a statement after it, so the docstring can go")
	}
}

