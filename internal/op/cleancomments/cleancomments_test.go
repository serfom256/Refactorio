func TestPlan_ApplyRemovesWholeLines(t *testing.T) {
	dir := t.TempDir()
	p := write(t, dir, "a.go", "package a\n\n// foo(x);\n// bar(y);\nfunc unused() {}\n")
	set, _, err := Plan([]string{p})
	if err != nil {
		t.Fatal(err)
	}
	if err := set.Apply(); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	want := "package a\n\nfunc unused() {}\n"
	if string(got) != want {
		t.Errorf("got %q, want %q", got, want)
	}
}

