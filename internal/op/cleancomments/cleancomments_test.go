func TestScan_GroupsConsecutiveLineComments(t *testing.T) {
	dir := t.TempDir()
	p := write(t, dir, "a.go", "package a\n\n// one\n// two\nfunc unused() {}\n")
	res, err := Scan(p)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Candidates) != 1 {
		t.Fatalf("got %d candidates, want the two lines grouped into 1", len(res.Candidates))
	}
	if res.Candidates[0].Lines() != 2 {
		t.Errorf("block covers %d lines, want 2", res.Candidates[0].Lines())
	}
}

func TestScan_DirectiveSurvivesAdjacentProse(t *testing.T) {
	dir := t.TempDir()
	p := write(t, dir, "a.go", "package a\n\n// Kind is a kind.\n//go:generate stringer -type=Kind\ntype Kind int\n")
	_, kept := scan(t, p)
	if len(kept) == 0 {
		t.Fatal("the directive was not kept")
	}
	set, _, err := Plan([]string{p})
	if err != nil {
		t.Fatal(err)
	}
	if err := set.Apply(); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadFile(p)
	if !strings.Contains(string(got), "//go:generate stringer -type=Kind") {
		t.Errorf("directive lost:\n%s", got)
	}
}

