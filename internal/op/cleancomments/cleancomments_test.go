package cleancomments

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func write(t *testing.T, dir, name, body string) string {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func scan(t *testing.T, path string) (removed, kept map[int]string) {
	t.Helper()
	res, err := Scan(path)
	if err != nil {
		t.Fatal(err)
	}
	removed, kept = map[int]string{}, map[int]string{}
	for _, c := range res.Candidates {
		removed[c.Line] = c.Text
	}
	for _, k := range res.Kept {
		kept[k.Line] = k.Reason
	}
	return removed, kept
}

func TestKeep_Directives(t *testing.T) {
	for _, text := range []string{
		"//go:generate stringer -type=Kind",
		"//go:embed templates",
		"//nolint:errcheck",
		"// +build linux",
		"# noqa: E501",
		"# type: ignore",
		"/* eslint-disable no-console */",
		"// @ts-expect-error the types disagree",
		"// prettier-ignore",
		"// Code generated by protoc. DO NOT EDIT.",
		"#!/usr/bin/env python3",
		"// revive:disable",
		"// clippy::needless_return",
	} {
		reason, ok := Keep(text)
		if !ok || reason != "directive" {
			t.Errorf("Keep(%q) = %q, %v; want directive, true", text, reason, ok)
		}
	}
}

